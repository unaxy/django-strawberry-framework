"""Hold basedpyright suppressions to the locks ``pyproject.toml`` sets and the site ledger.

basedpyright can only be told whether ignore comments are read at all: it has no
per-rule switch, keeps no count, and a file-level ``pyright:`` comment can lower any
rule for a whole file. This gate closes all three over every git-tracked ``.py`` file:

1. an ignore comment naming a rule ``[tool.basedpyright]`` marks ``# Locked``. Each
   locked rule is on and has no suppression in the tree, so its diagnostics are fixed
   at the root, never silenced;
2. any file-level ``pyright:`` directive (``basic``, ``reportFoo=false``, ...).
   ``[tool.basedpyright]`` owns every rule's level, file by file through its execution
   environments;
3. the ledger. ``scripts/type_suppressions.toml`` records, per site, how many
   ``typing.cast`` calls (``cast``) and how many ignore comments naming each unlocked
   rule the site holds. A site is the innermost symbol enclosing the suppression, keyed
   as a citation names it (``path::QualifiedName``, ``path`` alone at module level), so
   a suppression cannot move to new code by giving one up elsewhere. A count above its
   ledger entry, or at a site the ledger does not list, is a new suppression: fix the
   diagnostic instead. A count below it is a cleared one: ``--write`` lowers the entry
   so the cleared suppression cannot come back.

The ledger is generated, never edited by hand. ``--write`` rewrites it from the tree and
only ever lowers or drops an entry; it refuses to record a new or larger one unless
``--allow-new`` is passed, so every suppression a change adds or moves (a renamed symbol
moves its entries) is a deliberate, reviewable line in the ledger's diff. A rule whose
last suppression is cleared leaves the ledger and gains the ``# Locked`` marker once it
is on in every environment.

Only comment tokens are read, so a docstring or string that quotes a comment is not a
suppression; a ``cast`` call is one the AST resolves to ``typing.cast`` or
``typing_extensions.cast`` under any import alias.

Usage::

    uv run python scripts/check_type_suppressions.py
    uv run python scripts/check_type_suppressions.py --write [--allow-new]

Exit code ``1`` (each violation listed) on any violation, ``2`` when a file cannot be
read or parsed, ``pyproject.toml`` locks no rule, or the ledger is invalid.
"""

from __future__ import annotations

import argparse
import ast
import io
import json
import re
import subprocess
import sys
import tokenize
from collections import Counter
from pathlib import Path
from typing import TYPE_CHECKING, NamedTuple

import tomli

try:
    import check_citations
except ModuleNotFoundError:  # imported as a ``scripts`` submodule (repo root on path)
    from scripts import check_citations

if TYPE_CHECKING:
    from collections.abc import Callable, Iterable, Iterator, Sequence

    from typing_extensions import TypeIs

REPO_ROOT = Path(__file__).resolve().parents[1]
#: The generated site ledger, repo-relative.
LEDGER = "scripts/type_suppressions.toml"

#: ``report<Rule> = "<level>"  # Locked`` in ``[tool.basedpyright]``.
_LOCKED_LINE = re.compile(r'^(report\w+)\s*=\s*"\w+"\s*#\s*Locked\b', re.MULTILINE)

# basedpyright reads a directive at the start of a comment or after a further ``#``
# inside one (a ruff suppression, then the ignore).
_PYRIGHT_COMMENT = re.compile(r"(?:^|#)\s*pyright:\s*(?P<body>.*)")
_IGNORE = re.compile(r"ignore\s*(?:\[(?P<rules>[^\]]*)\])?")

#: The modules whose ``cast`` the ledger counts.
_CAST_MODULES = frozenset({"typing", "typing_extensions"})
#: The ledger kind of a ``typing.cast`` call; every other kind is a rule name.
CAST = "cast"

_HEADER = (
    "# Generated by scripts/check_type_suppressions.py --write; never edited by hand.\n"
    "# Each site (`path::QualifiedName`, `path` at module level) lists the `typing.cast`\n"
    "# calls (`cast`) and the ignore comments per rule it holds; a count may only fall.\n"
)


class _Args(argparse.Namespace):
    """The parsed command line: one field per ``parse_args`` argument."""

    write: bool
    allow_new: bool


class LedgerError(ValueError):
    """``pyproject.toml`` locks no rule, or the ledger is invalid."""


class Violation(NamedTuple):
    """One suppression the locks or the ledger refuse: where it is and what it does."""

    path: str
    line: int
    message: str


#: A ledger key: the site and the suppression kind (a rule name or ``cast``).
Entry = tuple[str, str]


def _is_toml_table(value: object) -> TypeIs[dict[str, object]]:
    """Return whether a decoded TOML value is a table (TOML table keys are always strings)."""
    return isinstance(value, dict)


def _table(document: object) -> dict[str, object]:
    """Return a decoded TOML document as the table it always is."""
    if not _is_toml_table(document):
        raise LedgerError(f"the ledger must be a table, not {document!r}")
    return document


def load_locked(pyproject: Path) -> frozenset[str]:
    """Return the rules ``[tool.basedpyright]`` in ``pyproject`` marks ``# Locked``.

    Raises:
        LedgerError: No rule is locked.

    """
    text = pyproject.read_text(encoding="utf-8")
    start = text.index("\n[tool.basedpyright]\n")
    end = text.find("\n[", start + 1)
    locked = frozenset(_LOCKED_LINE.findall(text[start : end if end != -1 else None]))
    if not locked:
        raise LedgerError("`[tool.basedpyright]` marks no rule `# Locked`")
    return locked


def load_ledger(ledger: Path, locked: frozenset[str]) -> Counter[Entry]:
    """Read the site ledger; an absent file is an empty ledger.

    Raises:
        LedgerError: A site is not a table, a count is not a positive integer, or an
            entry names a locked rule.

    """
    if not ledger.exists():
        return Counter()
    # ``tomli.loads`` returns ``dict[str, Any]``; this alias hands the walk an ``object``.
    toml_loads: Callable[[str], dict[str, object]] = tomli.loads
    counts: Counter[Entry] = Counter()
    for site, kinds in _table(toml_loads(ledger.read_text(encoding="utf-8"))).items():
        if not _is_toml_table(kinds):
            raise LedgerError(f"`{site}` must be a table of counts, not {kinds!r}")
        for kind, count in kinds.items():
            if isinstance(count, bool) or not isinstance(count, int) or count < 1:
                raise LedgerError(f"`{site}` `{kind}` must be a positive integer, not {count!r}")
            if kind in locked:
                raise LedgerError(f"`{site}` lists `{kind}`, which is locked")
            counts[site, kind] = count
    return counts


def render_ledger(counts: Counter[Entry]) -> str:
    """Return the ledger text for ``counts``: one sorted line per site."""
    sites: dict[str, dict[str, int]] = {}
    for (site, kind), count in sorted(counts.items()):
        if count:
            sites.setdefault(site, {})[kind] = count
    lines = [
        f"{json.dumps(site)} = {{ "
        + ", ".join(f"{kind} = {count}" for kind, count in kinds.items())
        + " }"
        for site, kinds in sites.items()
    ]
    return _HEADER + "\n" + "".join(f"{line}\n" for line in lines)


def _pyright_comments(source: str) -> Iterator[tuple[int, str]]:
    """Yield ``(line, body)`` for each ``pyright:`` directive among ``source``'s comments."""
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type != tokenize.COMMENT:
            continue
        for segment in token.string.split("#")[1:]:
            if (match := _PYRIGHT_COMMENT.match(f"#{segment}")) is not None:
                yield token.start[0], match.group("body").strip()


def ignored_rules(source: str) -> Iterator[tuple[int, str]]:
    """Yield ``(line, rule)`` for each rule an ignore comment in ``source`` names."""
    for line, body in _pyright_comments(source):
        if (ignore := _IGNORE.match(body)) is not None and ignore.group("rules"):
            for rule in ignore.group("rules").split(","):
                yield line, rule.strip()


def comment_violations(path: str, source: str, locked: frozenset[str]) -> Iterator[Violation]:
    """Yield every file-level directive and every ignore of a ``locked`` rule in ``source``."""
    for line, body in _pyright_comments(source):
        if _IGNORE.match(body) is None:
            yield Violation(
                path,
                line,
                f"file-level `# pyright: {body}` directive (pyproject.toml owns rule levels)",
            )
    for line, rule in ignored_rules(source):
        if rule in locked:
            yield Violation(
                path,
                line,
                f"`{rule}` is locked: fix the diagnostic, never suppress it",
            )


def cast_lines(source: str) -> Iterator[int]:
    """Yield the line of each call in ``source`` that resolves to ``typing.cast``, under any alias."""
    tree = ast.parse(source)
    names: set[str] = set()
    modules: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module in _CAST_MODULES:
            names.update(
                alias.asname or alias.name for alias in node.names if alias.name == "cast"
            )
        elif isinstance(node, ast.Import):
            modules.update(
                alias.asname or alias.name for alias in node.names if alias.name in _CAST_MODULES
            )
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and (
            (isinstance(node.func, ast.Name) and node.func.id in names)
            or (
                isinstance(node.func, ast.Attribute)
                and node.func.attr == "cast"
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id in modules
            )
        ):
            yield node.lineno


def suppressions(path: str, source: str) -> Iterator[tuple[int, Entry]]:
    """Yield ``(line, (site, kind))`` for every ignored rule and ``typing.cast`` call in ``source``."""
    found = [*ignored_rules(source), *((line, CAST) for line in cast_lines(source))]
    for line, kind in sorted(found):
        symbol = check_citations.enclosing_symbol(REPO_ROOT / path, line)
        yield line, (path if symbol is None else f"{path}::{symbol}", kind)


def ledger_violations(
    measured: Iterable[tuple[str, int, Entry]],
    ledger: Counter[Entry],
) -> Iterator[Violation]:
    """Yield each ``(site, kind)`` count, in site order, that differs from its ledger entry.

    ``measured`` holds one ``(path, line, entry)`` per suppression; an over-count points at
    the entry's first line in the tree, an under-count at the ledger.
    """
    counts: Counter[Entry] = Counter()
    first: dict[Entry, tuple[str, int]] = {}
    for path, line, entry in measured:
        counts[entry] += 1
        _ = first.setdefault(entry, (path, line))
    for entry in sorted(counts.keys() | ledger.keys()):
        site, kind = entry
        count, allowed = counts[entry], ledger[entry]
        if count > allowed:
            path, line = first[entry]
            yield Violation(
                path,
                line,
                f"`{kind}` at `{site}`: {count}, ledger {allowed}: "
                "fix the new diagnostic instead of suppressing it",
            )
        elif count < allowed:
            yield Violation(
                LEDGER,
                1,
                f"`{kind}` at `{site}`: {count}, ledger {allowed}: "
                f"run `scripts/check_type_suppressions.py --write`",
            )


def tracked_python_files() -> list[str]:
    """Every git-tracked ``.py`` file, repo-relative."""
    result = subprocess.run(
        ["git", "ls-files", "*.py"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.split()


def main(argv: Sequence[str] | None = None) -> int:
    """Check (or ``--write``) every tracked ``.py`` file against the locks and the ledger."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    _ = parser.add_argument(
        "--write",
        action="store_true",
        help="rewrite the ledger from the tree, lowering or dropping cleared entries",
    )
    _ = parser.add_argument(
        "--allow-new",
        action="store_true",
        help="with --write, also record new or larger entries",
    )
    args = parser.parse_args(argv, namespace=_Args())
    ledger_path = REPO_ROOT / LEDGER
    try:
        locked = load_locked(REPO_ROOT / "pyproject.toml")
        ledger = load_ledger(ledger_path, locked)
    except (OSError, ValueError, tomli.TOMLDecodeError) as error:
        print(f"{error}", file=sys.stderr)
        return 2
    paths = tracked_python_files()
    violations: list[Violation] = []
    measured: list[tuple[str, int, Entry]] = []
    for path in paths:
        try:
            source = (REPO_ROOT / path).read_text(encoding="utf-8")
            violations.extend(comment_violations(path, source, locked))
            # A locked rule's ignore is refused above; the ledger never lists one.
            measured.extend(
                (path, line, entry)
                for line, entry in suppressions(path, source)
                if entry[1] not in locked
            )
        except (
            OSError,
            UnicodeDecodeError,
            SyntaxError,
            tokenize.TokenError,
        ) as error:
            print(f"{path}: cannot check: {error}", file=sys.stderr)
            return 2
    drift = list(ledger_violations(measured, ledger))
    if args.write:
        growth = [v for v in drift if v.path != LEDGER]
        if growth and not args.allow_new:
            violations.extend(growth)
        elif not violations:
            _ = ledger_path.write_text(
                render_ledger(Counter(entry for _, _, entry in measured)),
                encoding="utf-8",
            )
    else:
        violations.extend(drift)
    for violation in violations:
        print(f"{violation.path}:{violation.line}: {violation.message}")
    casts = sum(entry[1] == CAST for _, _, entry in measured)
    print(
        f"type-suppressions: checked {len(paths)} file(s); ignore comments "
        f"{len(measured) - casts}, casts {casts}; violations {len(violations)}",
    )
    return 1 if violations else 0


if __name__ == "__main__":
    sys.exit(main())
